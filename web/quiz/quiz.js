/* "Which side business fits you?" — runs in the browser. The questions, points and businesses come from the
   page (generated by ops/seo/build_pages.js). Nothing is sent anywhere unless someone asks for the free course. */
(function(){
  var root = document.getElementById('quiz'), src = document.getElementById('quizData');
  if(!root || !src) return;
  var DATA = JSON.parse(src.textContent), Q = DATA.questions, B = DATA.businesses;
  var API = 'https://guide-backend-production.up.railway.app/api';
  var answers = [], at = 0;
  var esc = function(s){ return String(s == null ? '' : s).replace(/[&<>"']/g, function(c){ return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]; }); };
  var byId = function(id){ for(var i = 0; i < B.length; i++) if(B[i].id === id) return B[i]; return null; };

  function ask(){
    var q = Q[at];
    root.innerHTML =
      '<div class="qz-bar" role="progressbar" aria-valuemin="1" aria-valuemax="' + Q.length + '" aria-valuenow="' + (at + 1) + '"><i style="width:' + Math.round(at / Q.length * 100) + '%"></i></div>' +
      '<p class="pg-k">Question ' + (at + 1) + ' of ' + Q.length + '</p>' +
      '<h2 tabindex="-1">' + esc(q.q) + '</h2>' +
      '<div class="qz-opts">' + q.a.map(function(a, i){
        return '<button type="button" class="qz-opt' + (answers[at] === i ? ' on' : '') + '" data-i="' + i + '">' + esc(a.t) + '</button>';
      }).join('') + '</div>' +
      (at > 0 ? '<button type="button" class="qz-back">Back</button>' : '');
    var h = root.querySelector('h2'); if(at > 0 && h) h.focus({preventScroll: true});
  }

  function scores(){
    var s = {};
    B.forEach(function(b){ s[b.id] = 0; });
    answers.forEach(function(ai, qi){ var w = Q[qi].a[ai].w; for(var id in w) if(id in s) s[id] += w[id]; });
    return B.slice().sort(function(x, y){ return (s[y.id] - s[x.id]) || (B.indexOf(x) - B.indexOf(y)); });
  }

  function result(){
    var ranked = scores(), top = ranked[0], more = ranked.slice(1, 3);
    var picked = answers.map(function(ai, qi){ return Q[qi].a[ai].t; });
    var start = '/?start=' + encodeURIComponent(top.id) + '&utm_source=quiz&utm_medium=organic&utm_campaign=' + encodeURIComponent(top.id);
    var share = location.origin + '/quiz/' + top.slug + '/';
    root.innerHTML =
      '<p class="pg-k">Your best match</p>' +
      '<h2 class="qz-match" tabindex="-1">' + esc(top.name) + '</h2>' +
      '<p class="pg-lead">' + esc(top.line) + '</p>' +
      '<ul class="qz-why"><li>You want to work ' + esc(picked[0].toLowerCase()) + '</li><li>Budget: ' + esc(picked[1].toLowerCase()) + '</li><li>Time: ' + esc(picked[2].toLowerCase()) + ' hours a week</li></ul>' +
      (top.cost ? '<p class="qz-cost"><b>What it costs to start:</b> ' + esc(top.cost) + '</p>' : '') +
      (top.step ? '<div class="pg-step"><b>Your first step' + (top.lesson ? ': ' + esc(top.lesson) : '') + '</b><p>' + esc(top.step) + '</p></div>' : '') +
      '<div class="pg-ctas"><a class="pg-btn" href="' + start + '">Start Module 1 free</a><a class="pg-btn pg-btn-2" href="/start/' + top.slug + '/">Read the free guide</a></div>' +
      '<div class="qz-more"><p class="pg-k">Also worth a look</p><ul class="pg-list">' + more.map(function(b){
        return '<li><a href="/start/' + b.slug + '/"><b>' + esc(b.name) + '</b><span>' + esc(b.line) + '</span></a></li>';
      }).join('') + '</ul></div>' +
      '<form class="qz-mail" novalidate><label for="qzEmail">Get the free 7-day email course: one short step a day to get started</label>' +
        '<div class="qz-mail-row"><input type="email" id="qzEmail" placeholder="you@email.com" autocomplete="email" required>' +
        '<input type="text" name="website" tabindex="-1" autocomplete="off" class="qz-hp" aria-hidden="true">' +
        '<button type="submit" class="pg-btn">Send it</button></div><p class="qz-msg" role="status"></p></form>' +
      '<div class="pg-ctas"><button type="button" class="pg-btn pg-btn-2 qz-share">Share my result</button><button type="button" class="pg-btn pg-btn-2 qz-again">Take it again</button></div>';
    root.querySelector('.qz-match').focus({preventScroll: false});
    root.querySelector('.qz-again').addEventListener('click', function(){ answers = []; at = 0; ask(); root.scrollIntoView({block: 'start'}); });
    root.querySelector('.qz-share').addEventListener('click', function(){
      var btn = this, text = 'My side business match is ' + top.name + '. Which one is yours?';
      if(navigator.share){ navigator.share({ title: 'Which side business fits you?', text: text, url: share }).catch(function(){}); return; }
      (navigator.clipboard ? navigator.clipboard.writeText(share) : Promise.reject()).then(function(){ btn.textContent = 'Link copied'; }, function(){ prompt('Copy this link', share); });
    });
    var form = root.querySelector('.qz-mail');
    form.addEventListener('submit', function(e){
      e.preventDefault();
      var input = form.querySelector('#qzEmail'), msg = form.querySelector('.qz-msg'), email = input.value.trim();
      if(!/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)){ msg.textContent = 'Enter a real email address.'; input.focus(); return; }
      var b = form.querySelector('button'); b.disabled = true; msg.textContent = '';
      fetch(API + '/leads', { method: 'POST', headers: {'Content-Type': 'application/json'},
        body: JSON.stringify({ email: email, source: 'quiz-' + top.id, website: form.elements.website.value }) })
        .then(function(r){ return r.json().then(function(j){ return { ok: r.ok, j: j }; }); })
        .then(function(r){
          if(r.ok){ form.innerHTML = '<p class="qz-done"><b>Day 1 is on its way.</b> Check your inbox (and the spam folder, just in case).</p>'; }
          else { msg.textContent = (r.j && r.j.error) || 'Something went wrong. Please try again.'; b.disabled = false; }
        })
        .catch(function(){ msg.textContent = 'Could not send that just now. Please try again.'; b.disabled = false; });
    });
  }

  root.addEventListener('click', function(e){
    var opt = e.target.closest('.qz-opt');
    if(opt){ answers[at] = +opt.dataset.i; at++; if(at < Q.length) ask(); else result(); return; }
    if(e.target.closest('.qz-back')){ at = Math.max(0, at - 1); ask(); }
  });
  ask();
})();
