#!/usr/bin/env python3
"""Builds a web/niches/pack-N.js file from reviewed chapter files (see README.md).

    python3 ops/niches/build_pack.py --out web/niches/pack-1.js --label "batch 1" a.json b.json ...

- Every guide gets a stable 8-letter id (`vid`) made from the chapter id and the lesson title,
  checked against every id already in the app so none can clash.
- Tools come from ops/niches/tools.json.
- Chapters are validated first; nothing is written if any of them fails.
"""
import argparse, hashlib, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def existing_vids():
    files = [os.path.join(ROOT, 'web', 'index.html')]
    ndir = os.path.join(ROOT, 'web', 'niches')
    if os.path.isdir(ndir):
        files += [os.path.join(ndir, n) for n in os.listdir(ndir) if n.endswith('.js')]
    seen = set()
    for f in files:
        for a, b in re.findall(r'vid:\s*"([0-9a-f]{8})"|"vid":\s*"([0-9a-f]{8})"', open(f, encoding='utf-8').read()):
            seen.add(a or b)
    return seen


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--label', default='')
    ap.add_argument('files', nargs='+')
    a = ap.parse_args()
    tools = json.load(open(os.path.join(HERE, 'tools.json'), encoding='utf-8'))
    bad = 0
    for f in a.files:
        if subprocess.run([sys.executable, os.path.join(HERE, 'validate_niche.py'), f]).returncode:
            bad += 1
    if bad:
        sys.exit(f'{bad} chapter(s) failed the checks, nothing written.')
    seen = existing_vids()
    out_vids = set()
    chapters = []
    for f in a.files:
        d = json.load(open(f, encoding='utf-8'))
        cid = d['id']
        if cid not in tools['tools']:
            sys.exit(f'{cid}: no entry in ops/niches/tools.json')
        guides = []
        for g in d['guides']:
            n = 0
            while True:
                vid = hashlib.sha1(f'{cid}|{g["title"]}|{n}'.encode()).hexdigest()[:8]
                if vid not in seen and vid not in out_vids:
                    break
                n += 1
            out_vids.add(vid)
            guides.append({'vid': vid, **g})
        t = tools['tools'][cid]
        ch = {k: d[k] for k in ('id', 'name', 'icon', 'color', 'description')}
        ch['group'] = d['breakdown']['group']
        ch['breakdown'] = d['breakdown']
        ch['modules'] = d['modules']
        ch['checklists'] = d['checklists']
        ch['templates'] = d['templates']
        ch['videos'] = []
        ch['tools'] = t
        cfgs = {k: tools['specialtyConfigs'][k] for k in (t.get('specialty'), t.get('specialty2')) if k}
        if cfgs:
            ch['specialtyConfigs'] = cfgs
        ch['guides'] = guides
        chapters.append(ch)
    lines = [f'/* The Guide: new chapters{" (" + a.label + ")" if a.label else ""}.',
             '   Generated by ops/niches/build_pack.py from reviewed chapter files. Loaded by index.html before the app starts. */',
             '(window.NICHE_PACKS = window.NICHE_PACKS || []).push([']
    for i, ch in enumerate(chapters):
        head = {k: v for k, v in ch.items() if k != 'guides'}
        lines.append('{"chapter":' + json.dumps(head, ensure_ascii=False) + ',')
        lines.append(' "guides":[')
        lines.append(',\n'.join('  ' + json.dumps(g, ensure_ascii=False) for g in ch['guides']))
        lines.append(' ]}' + (',' if i < len(chapters) - 1 else ''))
    lines.append(']);')
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'wrote {a.out}: {len(chapters)} chapters, {sum(len(c["guides"]) for c in chapters)} guides')


if __name__ == '__main__':
    main()
